            product.colour
                ? `<p>Colour: ${product.colour}</p>`
                : "";

                const fruitText =
    product.fruit
        ? `<p>Preferred Fruit: ${product.fruit}</p>`
        : "";


        item.innerHTML = `

            <div class="cart-item-icon">

                <img
                    src="${product.icon}"
                    alt="${product.name}"
                >

            </div>


            <div class="cart-item-info">

                <strong>
                    ${product.name}
                </strong>

                ${sizeText}

                ${colourText}

                ${fruitText}

                <p>
                    ₹${product.price}
                </p>


                <div class="quantity-controls">

                    <button
                        onclick="changeQuantity(${index}, -1)">
                        −
                    </button>

                    <span>
                        ${product.quantity}
                    </span>

                    <button
                        onclick="changeQuantity(${index}, 1)">
                        +
                    </button>

                </div>

            </div>


            <button
                class="remove-item"
                onclick="removeFromCart(${index})">

                Remove

            </button>

        `;

